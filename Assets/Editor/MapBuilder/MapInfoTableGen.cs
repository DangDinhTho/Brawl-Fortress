using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEngine;

/// <summary>Writes Assets/Scripts/UI/Lobby/MapInfoTable.cs (map -> art theme, for the map info popup) from the
/// BrawlMapBuilder definitions plus the hand-made maps. Run Tools/Maps/Generate Map Info Table after adding maps.</summary>
public static class MapInfoTableGen
{
    const string OutPath = "Assets/Scripts/UI/Lobby/MapInfoTable.cs";

    /// <summary>Maps built by hand (no BrawlMapBuilder definition) and the theme they look like.</summary>
    static readonly (string map, string theme)[] HandMade =
    {
        ("BrawlScene", "Western"), ("BrawlScene_2", "Bamboo"), ("Map_Brawl_ShowDown", "Moon"), ("Map_Brawl_CTF", "Moon"),
        ("Map_Brawl_Koth", "Bamboo"), ("Map_Brawl_Payload", "Cave"), ("Map_Brawl_MvM", "Western"),
    };

    [MenuItem("Tools/Maps/Generate Map Info Table")]
    public static void Generate()
    {
        if (!Application.dataPath.Contains("Brawl Fortress")) return;
        var rows = new List<(string, string)>(HandMade);
        // BossZombie (Boss Battle / Zombie maps of the old themes) is not part of AllDefs(): list it too, or those maps
        // lose their theme in the info popup
        foreach (var d in BrawlMapBuilder.AllDefs().Concat(BrawlMapBuilder.BossZombie))
            if (rows.All(r => r.Item1 != d.mapEnum)) rows.Add((d.mapEnum, d.theme + (d.night ? "Night" : "")));
        var sb = new StringBuilder();
        sb.Append("// <auto-generated> by Tools/Maps/Generate Map Info Table (Assets/Editor/MapBuilder/MapInfoTableGen.cs) from the\r\n");
        sb.Append("// BrawlMapBuilder map definitions plus the hand-made maps. Do not edit by hand: run the menu after adding maps.\r\n");
        sb.Append("using System.Collections.Generic;\r\n\r\npublic static class MapInfoTable\r\n{\r\n");
        sb.Append("    /// <summary>Art theme of each map: a BrawlMapBuilder.Theme name, \"XmasNight\" for the Christmas night maps.</summary>\r\n");
        sb.Append("    public static readonly Dictionary<Map, string> Theme = new Dictionary<Map, string>\r\n    {\r\n");
        foreach (var (m, t) in rows) sb.Append("        { Map." + m + ", \"" + t + "\" },\r\n");
        sb.Append("    };\r\n}\r\n");
        File.WriteAllText(OutPath, sb.ToString(), new UTF8Encoding(false));
        AssetDatabase.ImportAsset(OutPath);
        Debug.Log("[MapInfoTable] " + rows.Count + " maps written to " + OutPath);
    }
}
